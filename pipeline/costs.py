"""Build the measured tables in COSTS.md from runs.jsonl.

Nothing in those tables is typed by hand. The log stores cost in each
provider's own unit (tokens, neurons, GPU seconds); this script applies the
list prices in pipeline/pricing.json to say what the free usage would have
cost, and writes the result between two markers in COSTS.md.
"""
from __future__ import annotations

import json
import statistics
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from .common import config, runlog

COSTS = config.ROOT / "COSTS.md"
PRICING = Path(__file__).with_name("pricing.json")
BEGIN, END = "<!-- costs:begin (generated by `make costs`; do not edit by hand) -->", "<!-- costs:end -->"
STAGE_ORDER = ["smoke", "script", "radio", "narration", "refs", "keyframes", "shots", "music"]


def call_price(record: dict[str, Any], pricing: dict[str, Any]) -> float:
    """List-price equivalent of one logged call, in US dollars."""
    cost = record.get("cost") or {}
    unit = cost.get("unit")
    if unit == "tokens":
        price = pricing["gemini"]["models"].get(record.get("model"))
        if not price:
            return 0.0
        return ((cost.get("input") or 0) * price["input_per_million"]
                + (cost.get("output") or 0) * price["output_per_million"]) / 1_000_000
    if unit == "neurons":
        return (cost.get("amount") or 0) * pricing["cloudflare"]["per_thousand_neurons"] / 1000
    if unit == "gpu_seconds":
        return (cost.get("amount") or 0) * pricing["gpu"]["t4_per_hour"] / 3600
    return 0.0


def summarise(records: list[dict[str, Any]], pricing: dict[str, Any]) -> dict[str, Any]:
    stages: dict[str, dict[str, Any]] = defaultdict(lambda: {
        "calls": 0, "ok": 0, "failed": 0, "latencies": [], "tokens_in": 0, "tokens_out": 0,
        "neurons": 0.0, "gpu_seconds": 0.0, "usd": 0.0, "models": set(),
    })
    jobs = {"count": 0, "session_seconds": 0.0, "wall_seconds": 0.0, "failed": 0}
    experiments: dict[str, int] = defaultdict(int)

    for record in records:
        event = record.get("event")
        if event == "remote_job":
            jobs["count"] += 1
            jobs["wall_seconds"] += float(record.get("wall_s") or 0)
            jobs["session_seconds"] += float(record.get("remote_elapsed_s") or 0)
            if record.get("status") != "complete":
                jobs["failed"] += 1
            continue
        if event != "model_call":
            continue
        stage = stages[record.get("stage") or "unknown"]
        stage["calls"] += 1
        stage["models"].add(str(record.get("model")))
        ok = record.get("status") == "ok"
        stage["ok" if ok else "failed"] += 1
        if record.get("experiment_id"):
            experiments[record["experiment_id"]] += 1
        cost = record.get("cost") or {}
        if cost.get("unit") == "tokens":  # Gemini bills failed calls nothing; tokens are only present on success
            stage["tokens_in"] += cost.get("input") or 0
            stage["tokens_out"] += cost.get("output") or 0
        if not ok:
            continue
        if record.get("latency_s") is not None:
            stage["latencies"].append(float(record["latency_s"]))
        if cost.get("unit") == "neurons":
            stage["neurons"] += float(cost.get("amount") or 0)
        if cost.get("unit") == "gpu_seconds":
            stage["gpu_seconds"] += float(cost.get("amount") or 0)
        stage["usd"] += call_price(record, pricing)

    session_usd = jobs["session_seconds"] * 2 * pricing["gpu"]["t4_per_hour"] / 3600  # a session holds two T4s
    return {"stages": stages, "jobs": jobs, "experiments": dict(experiments), "session_usd": session_usd}


def frontier(summary: dict[str, Any], records: list[dict[str, Any]], pricing: dict[str, Any]) -> list[tuple[str, str, str, str]]:
    """What the same outputs would cost on the paid frontier models. A paper comparison."""
    front = pricing["frontier"]
    ok = [r for r in records if r.get("event") == "model_call" and r.get("status") == "ok"]
    images = sum(1 for r in ok if r.get("provider") == "cloudflare")
    clip_seconds = sum((r.get("params") or {}).get("num_frames", 0) / config.FPS
                       for r in ok if r.get("stage") == "shots")
    songs = sum(1 for r in ok if r.get("stage") == "music")
    stages = summary["stages"]
    ours_images = sum(stages[s]["usd"] for s in ("refs", "keyframes", "smoke") if s in stages and stages[s]["neurons"])
    return [
        ("Images", f"{images}", f"${ours_images:.4f} (FLUX.2 klein 4B)",
         f"${images * front['image']['price']:.2f} ({front['image']['model']}, {front['image']['unit']})"),
        ("Video", f"{clip_seconds:.0f} s", f"${stages['shots']['usd'] if 'shots' in stages else 0:.4f} (Wan 2.2 on a T4)",
         f"${clip_seconds * front['video']['price']:.2f} ({front['video']['model']}, per {front['video']['unit']})"),
        ("Music", f"{songs} track{'' if songs == 1 else 's'}", f"${stages['music']['usd'] if 'music' in stages else 0:.4f} (ACE-Step 1.5 on a T4)",
         f"${songs * front['music']['price']:.2f} ({front['music']['model']}, per {front['music']['unit']})"),
    ]


def render(records: list[dict[str, Any]], pricing: dict[str, Any]) -> str:
    summary = summarise(records, pricing)
    stages, jobs = summary["stages"], summary["jobs"]
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    calls = sum(s["calls"] for s in stages.values())
    lines = [BEGIN, "", f"Generated {now} from {len(records)} log lines ({calls} model call attempts).", ""]

    if not calls:
        lines += ["No model calls have been logged yet.", "", END]
        return "\n".join(lines)

    lines += [
        "### Per stage",
        "",
        "| Stage | Model | Calls | Failed | Median latency | Total latency | Units used | List-price equivalent |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    ordered = [s for s in STAGE_ORDER if s in stages] + sorted(s for s in stages if s not in STAGE_ORDER)
    total_usd = 0.0
    for name in ordered:
        stage = stages[name]
        latencies = stage["latencies"]
        median = f"{statistics.median(latencies):.1f} s" if latencies else "n/a"
        units = []
        if stage["tokens_in"] or stage["tokens_out"]:
            units.append(f"{stage['tokens_in']:,} in / {stage['tokens_out']:,} out tokens")
        if stage["neurons"]:
            units.append(f"{stage['neurons']:,.0f} neurons (estimated)")
        if stage["gpu_seconds"]:
            units.append(f"{stage['gpu_seconds'] / 60:.1f} GPU minutes")
        total_usd += stage["usd"]
        lines.append(
            f"| {name} | {', '.join(sorted(stage['models']))} | {stage['calls']} | {stage['failed']} | {median} "
            f"| {sum(latencies):.0f} s | {'; '.join(units) or 'n/a'} | ${stage['usd']:.4f} |"
        )
    lines += ["", f"List-price equivalent of every successful call: **${total_usd:.2f}**. Amount actually paid: **$0**.", ""]

    lines += [
        "### GPU time on Kaggle",
        "",
        "| Measure | Value |",
        "| --- | --- |",
        f"| Jobs run | {jobs['count']} ({jobs['failed']} did not complete) |",
        f"| GPU session time (counts against the weekly quota) | {jobs['session_seconds'] / 60:.1f} minutes |",
        f"| Of which generating (sum of per-clip and per-track time) | "
        f"{sum(s['gpu_seconds'] for s in stages.values()) / 60:.1f} GPU minutes |",
        f"| Local wall-clock time waiting, including queueing | {jobs['wall_seconds'] / 60:.1f} minutes |",
        f"| Session time at list price, two T4s | ${summary['session_usd']:.2f} (T4 price unverified, see below) |",
        "",
        "The gap between session time and generating time is setup: installing libraries, downloading the model, loading it.",
        "",
    ]

    lines += [
        "### Paper comparison with paid frontier models",
        "",
        "We had no access to these models, so nothing here was measured on them. The table prices our output counts at their list prices.",
        "",
        "| Output | Amount we generated | Our list-price equivalent | The same amount on the frontier model |",
        "| --- | --- | --- | --- |",
    ]
    lines += [f"| {a} | {b} | {c} | {d} |" for a, b, c, d in frontier(summary, records, pricing)]
    lines += ["", "The amounts include every candidate, retry and experiment, not only what is in the final film.", ""]

    if summary["experiments"]:
        tagged = ", ".join(f"{k}: {v}" for k, v in sorted(summary["experiments"].items()))
        lines += [f"Model calls tagged with an experiment id: {tagged}.", ""]
    lines.append(END)
    return "\n".join(lines)


def main() -> int:
    pricing = json.loads(PRICING.read_text(encoding="utf-8"))
    block = render(runlog.read(), pricing)
    text = COSTS.read_text(encoding="utf-8") if COSTS.exists() else f"# Costs\n\n{BEGIN}\n{END}\n"
    if BEGIN in text and END in text:
        text = text[:text.index(BEGIN)] + block + text[text.index(END) + len(END):]
    else:
        text = text.rstrip() + "\n\n" + block + "\n"
    COSTS.write_text(text, encoding="utf-8")
    print(f"Updated {config.rel(COSTS)} from {config.rel(config.RUNS)}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
